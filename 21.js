let nomes = ["Kimi", "Max", "Gabriel", "George", "Charles", "Lewis", "Olive", "Fernando"];

console.log("Lista original:");
console.log(nomes);

nomes.sort();

console.log("Lista ordenada:");
console.log(nomes);

nomes.reverse();

console.log("Lista invertida:");
console.log(nomes);

let resultado = nomes.join(", ");

console.log("Resultado em string:");
console.log(resultado);